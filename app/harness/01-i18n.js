let CURRENT_LANG = (function() {
  try { const s = localStorage.getItem(I18N_KEY); if (s === 'zh' || s === 'en') return s; } catch {}
  const nav = (navigator.language || '').toLowerCase();
  return nav.startsWith('zh') ? 'zh' : 'en';
})();
function t(key, fallback) {
  const dict = I18N[CURRENT_LANG] || I18N.en;
  if (dict[key] != null) return dict[key];
  if (I18N.en[key] != null) return I18N.en[key];
  return fallback != null ? fallback : key;
}
function applyI18n(root) {
  const scope = root || document;
  scope.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (!key) return;
    el.textContent = t(key, el.textContent);
  });
  scope.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    if (!key) return;
    el.innerHTML = t(key, el.innerHTML);
  });
  scope.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (!key) return;
    el.setAttribute('title', t(key, el.getAttribute('title') || ''));
  });
  scope.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (!key) return;
    el.setAttribute('placeholder', t(key, el.getAttribute('placeholder') || ''));
  });
  document.documentElement.setAttribute('lang', CURRENT_LANG === 'zh' ? 'zh-CN' : 'en');
}
function setLanguage(lang) {
  if (lang !== 'en' && lang !== 'zh') return;
  CURRENT_LANG = lang;
  try { localStorage.setItem(I18N_KEY, lang); } catch {}
  applyI18n();
  // Refresh dynamic UI pieces
  try { if (typeof updateLangButton === 'function') updateLangButton(); } catch {}
  try { if (typeof setStatus === 'function' && !isGenerating) setStatus('ready', t('status.ready')); } catch {}
  try { if (typeof updateMemoryUI === 'function') updateMemoryUI(); } catch {}
  try { if (typeof updateWsStatus === 'function') updateWsStatus(); } catch {}
  try { if (typeof renderMcpToolList === 'function') renderMcpToolList(); } catch {}
  try { if (typeof _updateSyncStatus === 'function') _updateSyncStatus(); } catch {}
}
function toggleLanguage() { setLanguage(CURRENT_LANG === 'zh' ? 'en' : 'zh'); }
function updateLangButton() {
  const btn = document.getElementById('langBtn');
  if (!btn) return;
  const label = btn.querySelector('[data-role="lang-label"]');
  if (label) label.textContent = CURRENT_LANG === 'zh' ? '中' : 'EN';
  btn.setAttribute('title', t('btn.langTitle'));
}

